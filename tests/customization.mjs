import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE_PATH ? pathToFileURL(process.env.PLAYWRIGHT_MODULE_PATH).href : 'playwright-core');
const browser = await chromium.launch({ executablePath: process.env.BROWSER_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const base = process.env.TEST_URL || 'http://127.0.0.1:4173/';
const out = resolve(process.env.TEST_ARTIFACTS || 'test-results');
await mkdir(out, { recursive: true });
const checks = [], errors = [];
const check = (condition, name) => { assert.ok(condition, name); checks.push(name); };
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'no-preference' });
  const page = await context.newPage(); page.on('pageerror', error => errors.push(error.message));
  await page.goto(base); await page.waitForSelector('html[data-ready=true]');
  await page.locator('#customize-toggle').click();
  check(await page.locator('#customize-panel').isVisible(), 'Customization panel opens');
  check(await page.locator('[data-feature-control]').count() === 19, 'All 19 feature switches are available');
  await page.locator('#feature-heroScene').uncheck();
  check(await page.locator('#hero-stage').isHidden(), 'Hero disappears immediately without navigation/reload');
  check(await page.locator('#hero-title .split-word').first().evaluate(el => getComputedStyle(el).animationName === 'none'), 'Unrelated feature changes do not replay heading entrances');
  await page.locator('#feature-heroScene').check();
  await page.waitForSelector('#hero-stage[data-ready=true]');
  check(true, 'Hero renders again when reenabled');
  await page.locator('#feature-objectShowcase').uncheck();
  check(await page.locator('#objects').isHidden() && await page.locator('[data-menu-link][href="#objects"]').isHidden(), 'Disabling playground also hides its navigation');
  await page.locator('#feature-objectShowcase').check();
  check(await page.locator('#objects').isVisible(), 'Playground is restored live');
  await page.locator('#feature-projectCarousel').uncheck();
  check(await page.locator('#project-rail').evaluate(el => el.classList.contains('is-grid')), 'Carousel switch immediately restores a project grid');
  await page.locator('#feature-projectCarousel').check();
  check(await page.locator('#project-rail').evaluate(el => !el.classList.contains('is-grid')), 'Carousel can be restored live');
  await page.locator('#feature-localClock').uncheck();
  await page.locator('#feature-localClock').check();
  check(await page.locator('#local-clock').isVisible(), 'Clock is restored after off/on');
  await page.locator('#feature-scrollReveals').uncheck();
  await page.locator('#feature-scrollReveals').check();
  check(await page.locator('.reveal-pending').count() > 0, 'Reenabled scroll reveals are armed again');
  await page.locator('#feature-storyCollage').uncheck();
  await page.reload(); await page.waitForSelector('html[data-ready=true]');
  check(await page.locator('.story-collage').isHidden(), 'Temporary feature preferences persist in this browser');
  await page.locator('#customize-toggle').click();
  await page.locator('#features-off').click();
  check(await page.locator('[data-feature-control]:checked').count() === 0, 'All off disables every optional feature');
  check(await page.locator('#menu-toggle').isHidden() && await page.locator('#objects').isHidden(), 'All off removes menu and 3D section');
  check(await page.locator('#customize-toggle').isVisible(), 'Customizer remains available when everything is off');
  await page.locator('#features-on').click();
  check(await page.locator('[data-feature-control]:checked').count() === 19, 'All on restores every optional feature');
  await page.locator('#features-reset').click();
  check(await page.evaluate(() => localStorage.getItem('bb-feature-preview-v1') === null), 'Reset removes stored overrides');
  // Leave the panel visible for a representative desktop capture.
  await page.waitForTimeout(1100);
  await page.locator('#customize-options').evaluate(el => el.parentElement.scrollTo(0, 0));
  await page.screenshot({ path: resolve(out, 'customization-desktop.png') });
  await page.locator('#customize-close').click();
  check(await page.locator('#customize-toggle').evaluate(el => el === document.activeElement), 'Closing customization returns focus');

  await page.locator('#menu-toggle').click();
  check(await page.locator('#menu-toggle').evaluate(el => Boolean(el.closest('#site-menu'))), 'The original hamburger remains available inside the open menu');
  await page.waitForFunction(() => document.querySelector('#site-menu').dataset.phase === 'open');
  await page.locator('#menu-toggle').click();
  check(await page.locator('#site-menu').evaluate(el => el.open && el.dataset.phase === 'closing'), 'Second hamburger click starts a closing animation');
  const clip = await page.locator('#site-menu').evaluate(el => getComputedStyle(el).clipPath);
  check(clip.startsWith('ellipse('), 'Closing uses the same ellipse reveal shape as opening');
  await page.waitForFunction(() => !document.querySelector('#site-menu').open);
  check(await page.locator('#menu-toggle').evaluate(el => Boolean(el.closest('#site-header')) && el === document.activeElement), 'Hamburger returns to header with focus after closing');
  // Dispatch immediately to exercise interruption rather than Playwright waiting for animation stability.
  await page.locator('#menu-toggle').evaluate(el => { el.click(); el.click(); el.click(); });
  await page.waitForFunction(() => document.querySelector('#site-menu').dataset.phase === 'open');
  check(await page.locator('#site-menu').evaluate(el => el.open), 'Rapid toggles can reverse a closing menu safely');
  await page.keyboard.press('Escape'); await page.waitForFunction(() => !document.querySelector('#site-menu').open);
  check(await page.evaluate(() => !document.documentElement.classList.contains('menu-open') && getComputedStyle(document.documentElement).overflow !== 'hidden'), 'Escape animates close and releases scroll lock');
  await context.close();

  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, reducedMotion: 'reduce' });
  const mp = await mobile.newPage(); mp.on('pageerror', error => errors.push(error.message));
  await mp.goto(base); await mp.waitForSelector('html[data-ready=true]');
  await mp.locator('#customize-toggle').click();
  check(await mp.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile customizer fits the viewport');
  check(await mp.locator('#customize-panel').evaluate(el => el.getBoundingClientRect().height <= innerHeight * .51), 'Mobile panel leaves the site visible above it');
  await mp.screenshot({ path: resolve(out, 'customization-mobile.png') });
  await mp.locator('#feature-heroScene').uncheck();
  check(await mp.locator('#hero-stage').isHidden(), 'Mobile feature switches apply live');
  await mp.locator('#features-reset').click();
  await mp.locator('#customize-close').click();
  await mp.locator('#menu-toggle').click();
  await mp.locator('#menu-toggle').click();
  check(await mp.locator('#site-menu').evaluate(el => !el.open), 'Reduced-motion menu closes immediately');
  check(await mp.locator('html').getAttribute('data-motion') === 'off', 'Live customization retains system reduced-motion preference');
  await mobile.close();
  const direct = await browser.newPage();
  await direct.goto(`${base}?customize=1`);
  await direct.waitForSelector('html[data-ready=true]');
  check(await direct.locator('#customize-panel').isVisible(), 'Direct customization URL opens the live panel');
  await direct.close();
  check(errors.length === 0, 'No page errors during live reconfiguration or interrupted animations');
  await writeFile(resolve(out, 'customization-validation.json'), JSON.stringify({ passed: checks.length, checks, errors }, null, 2));
  console.log(JSON.stringify({ passed: checks.length, errors, artifacts: out }));
} catch (error) { console.error(error); console.error(JSON.stringify({ checks, errors })); process.exitCode = 1; }
finally { await browser.close(); }
